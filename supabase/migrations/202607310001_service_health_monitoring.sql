-- Service health monitoring. Safe defaults preserve existing ordering.
alter table public.services
  add column if not exists health_status text not null default 'stable',
  add column if not exists health_message text,
  add column if not exists accepts_new_orders boolean not null default true,
  add column if not exists last_tested_at timestamptz,
  add column if not exists health_updated_at timestamptz not null default now();

alter table public.services drop constraint if exists services_health_status_check;
alter table public.services add constraint services_health_status_check
  check (health_status in ('stable','high_demand','slower_delivery','limited','paused','maintenance'));

create table if not exists public.service_health_history (
  id bigint generated by default as identity primary key,
  service_id bigint not null references public.services(id) on delete cascade,
  previous_status text,
  new_status text not null,
  changed_by uuid references public.profiles(id) on delete set null,
  internal_reason text,
  changed_at timestamptz not null default now()
);

create index if not exists service_health_history_service_changed_idx
  on public.service_health_history(service_id, changed_at desc);

alter table public.service_health_history enable row level security;
drop policy if exists "service_health_history_admin_select" on public.service_health_history;
create policy "service_health_history_admin_select" on public.service_health_history
  for select to authenticated using (public.is_admin());
drop policy if exists "service_health_history_admin_insert" on public.service_health_history;
create policy "service_health_history_admin_insert" on public.service_health_history
  for insert to authenticated with check (public.is_admin() and changed_by = auth.uid());

create or replace function public.reject_paused_service_order()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_allowed boolean;
begin
  select (accepts_new_orders and health_status <> 'paused') into v_allowed
  from public.services where id = new.service_id;
  if coalesce(v_allowed, false) = false then
    raise exception 'This service is temporarily unavailable for new orders';
  end if;
  return new;
end;
$$;

drop trigger if exists reject_paused_service_order_trigger on public.orders;
create trigger reject_paused_service_order_trigger
  before insert on public.orders for each row execute function public.reject_paused_service_order();

