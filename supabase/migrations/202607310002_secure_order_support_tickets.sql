-- Structured, order-aware support tickets with protected customer transitions.
alter table public.support_tickets
  add column if not exists order_id uuid references public.orders(id) on delete set null,
  add column if not exists last_reply_at timestamptz,
  add column if not exists resolved_at timestamptz;

update public.support_tickets set status = case status
  when 'pending' then 'waiting_for_support'
  when 'answered' then 'waiting_for_customer'
  when 'solved' then 'resolved'
  else status end
where status in ('pending','answered','solved');

alter table public.support_tickets drop constraint if exists support_tickets_status_check;
alter table public.support_tickets add constraint support_tickets_status_check
  check (status in ('open','waiting_for_support','waiting_for_customer','resolved','closed'));

create index if not exists support_tickets_order_category_idx
  on public.support_tickets(order_id, category, status);

create table if not exists public.support_internal_notes (
  id bigint generated by default as identity primary key,
  ticket_id uuid not null references public.support_tickets(id) on delete cascade,
  admin_id uuid references public.profiles(id) on delete set null,
  note text not null check (char_length(note) between 1 and 5000),
  created_at timestamptz not null default now()
);
alter table public.support_internal_notes enable row level security;
drop policy if exists "support_internal_notes_admin_select" on public.support_internal_notes;
create policy "support_internal_notes_admin_select" on public.support_internal_notes for select to authenticated using (public.is_admin());
drop policy if exists "support_internal_notes_admin_insert" on public.support_internal_notes;
create policy "support_internal_notes_admin_insert" on public.support_internal_notes for insert to authenticated with check (public.is_admin() and admin_id = auth.uid());

drop policy if exists "tickets_insert_own" on public.support_tickets;
drop policy if exists "tickets_update_own_or_admin" on public.support_tickets;
drop policy if exists "tickets_admin_update" on public.support_tickets;
create policy "tickets_admin_update" on public.support_tickets for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "messages_insert_ticket_participant" on public.support_messages;
create policy "messages_insert_ticket_participant" on public.support_messages for insert to authenticated with check (
  sender_id = auth.uid() and (public.is_admin() or exists (
    select 1 from public.support_tickets t where t.id = ticket_id and t.user_id = auth.uid() and t.status not in ('resolved','closed')
  ))
);

create or replace function public.create_support_ticket(
  p_category text, p_subject text, p_message text, p_order_id uuid default null
) returns uuid language plpgsql security definer set search_path = public as $$
declare v_user uuid := auth.uid(); v_ticket uuid; v_order public.orders%rowtype;
begin
  if v_user is null then raise exception 'Authentication required'; end if;
  if p_category not in ('order_pending','partial_delivery','drop_or_refill','incorrect_public_link','cancellation_request','payment_or_wallet','account_issue','service_availability','other') then raise exception 'Invalid issue category'; end if;
  if char_length(trim(p_subject)) < 3 or char_length(trim(p_message)) < 1 then raise exception 'Subject and message are required'; end if;
  if p_order_id is not null then
    select * into v_order from public.orders where id = p_order_id and user_id = v_user;
    if not found then raise exception 'Related order not found'; end if;
    if p_category = 'drop_or_refill' and not coalesce(v_order.refill_eligible, false) then raise exception 'This order is not currently eligible for refill.'; end if;
    if exists (select 1 from public.support_tickets where user_id=v_user and order_id=p_order_id and category=p_category and status in ('open','waiting_for_support','waiting_for_customer')) then raise exception 'You already have an active support request for this issue.'; end if;
  elsif p_category in ('order_pending','partial_delivery','drop_or_refill','incorrect_public_link','cancellation_request') then
    raise exception 'A related order is required for this issue';
  end if;
  insert into public.support_tickets(user_id,order_id,category,subject,status,updated_at,last_reply_at)
  values(v_user,p_order_id,p_category,trim(p_subject),'waiting_for_support',now(),now()) returning id into v_ticket;
  insert into public.support_messages(ticket_id,sender_id,message) values(v_ticket,v_user,trim(p_message));
  return v_ticket;
end; $$;

create or replace function public.reply_to_support_ticket(p_ticket_id uuid, p_message text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not exists(select 1 from public.support_tickets where id=p_ticket_id and user_id=auth.uid() and status not in ('resolved','closed')) then raise exception 'Ticket is closed or unavailable'; end if;
  insert into public.support_messages(ticket_id,sender_id,message) values(p_ticket_id,auth.uid(),trim(p_message));
  update public.support_tickets set status='waiting_for_support',updated_at=now(),last_reply_at=now() where id=p_ticket_id;
end; $$;

create or replace function public.resolve_my_support_ticket(p_ticket_id uuid)
returns void language sql security definer set search_path = public as $$
  update public.support_tickets set status='resolved',resolved_at=now(),updated_at=now() where id=p_ticket_id and user_id=auth.uid() and status <> 'closed';
$$;

revoke all on function public.create_support_ticket(text,text,text,uuid) from public;
revoke all on function public.reply_to_support_ticket(uuid,text) from public;
revoke all on function public.resolve_my_support_ticket(uuid) from public;
grant execute on function public.create_support_ticket(text,text,text,uuid) to authenticated;
grant execute on function public.reply_to_support_ticket(uuid,text) to authenticated;
grant execute on function public.resolve_my_support_ticket(uuid) to authenticated;

