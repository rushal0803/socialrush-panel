-- Production order fulfillment tracking. Idempotent and data-preserving.

alter table public.orders add column if not exists starting_count bigint;
alter table public.orders add column if not exists current_count bigint;
alter table public.orders add column if not exists delivered_count bigint;
alter table public.orders add column if not exists remaining_count bigint;
alter table public.orders add column if not exists progress_percent numeric(6,2);
alter table public.orders add column if not exists count_detection_status text;
alter table public.orders add column if not exists count_detection_source text;
alter table public.orders add column if not exists count_detection_message text;
alter table public.orders add column if not exists admin_note text;
alter table public.orders add column if not exists customer_note text;
alter table public.orders add column if not exists refill_eligible boolean not null default false;
alter table public.orders add column if not exists refill_requested_at timestamptz;
alter table public.orders add column if not exists last_count_checked_at timestamptz;
alter table public.orders add column if not exists completed_at timestamptz;
alter table public.orders add column if not exists failed_reason text;
alter table public.orders add column if not exists partial_quantity_delivered bigint;
alter table public.orders add column if not exists refund_credit_note text;
alter table public.orders add column if not exists payment_status text not null default 'paid';

update public.orders
set
  starting_count = case when coalesce(start_count, 0) > 0 then start_count else starting_count end,
  remaining_count = coalesce(remaining_count, remains, quantity),
  admin_note = coalesce(admin_note, admin_notes),
  customer_note = coalesce(customer_note, notes)
where starting_count is null
   or remaining_count is null
   or admin_note is null
   or customer_note is null;

alter table public.orders drop constraint if exists orders_status_check;
alter table public.orders add constraint orders_status_check check (status in (
  'pending', 'processing', 'in_progress', 'partial', 'completed', 'cancelled',
  'refunded', 'failed', 'refill_requested', 'refilling'
));

alter table public.orders drop constraint if exists orders_count_detection_status_check;
alter table public.orders add constraint orders_count_detection_status_check
  check (count_detection_status is null or count_detection_status in ('pending', 'detected', 'failed', 'manual'));

create or replace function public.calculate_order_progress()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_delivered bigint;
begin
  if new.starting_count is not null and new.current_count is not null then
    v_delivered := greatest(new.current_count - new.starting_count, 0);
  elsif new.partial_quantity_delivered is not null then
    v_delivered := greatest(new.partial_quantity_delivered, 0);
  else
    v_delivered := null;
  end if;

  new.delivered_count := v_delivered;
  new.remaining_count := case
    when v_delivered is null then coalesce(new.remaining_count, new.quantity)
    else greatest(new.quantity - v_delivered, 0)
  end;
  new.progress_percent := case
    when new.quantity > 0 and v_delivered is not null
      then least(100, round((v_delivered::numeric / new.quantity::numeric) * 100, 2))
    else null
  end;

  -- Keep legacy fields synchronized for older customer components.
  new.start_count := coalesce(new.starting_count, 0);
  new.remains := coalesce(new.remaining_count, new.quantity);
  new.admin_notes := new.admin_note;
  new.notes := new.customer_note;

  if new.status = 'completed' and new.completed_at is null then new.completed_at := now(); end if;
  if new.status = 'refill_requested' and new.refill_requested_at is null then new.refill_requested_at := now(); end if;
  return new;
end;
$$;

drop trigger if exists calculate_order_progress on public.orders;
create trigger calculate_order_progress
before insert or update on public.orders
for each row execute function public.calculate_order_progress();

create table if not exists public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  previous_status text,
  status text not null,
  note text,
  changed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.order_status_history enable row level security;
drop policy if exists "order_history_select_owner_or_admin" on public.order_status_history;
create policy "order_history_select_owner_or_admin" on public.order_status_history
for select to authenticated using (
  public.is_admin() or exists (
    select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid()
  )
);
drop policy if exists "order_history_admin_insert" on public.order_status_history;
create policy "order_history_admin_insert" on public.order_status_history
for insert to authenticated with check (public.is_admin());

create or replace function public.record_order_status_history()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if tg_op = 'INSERT' or old.status is distinct from new.status then
    insert into public.order_status_history(order_id, previous_status, status, note, changed_by)
    values (
      new.id,
      case when tg_op = 'UPDATE' then old.status else null end,
      new.status,
      coalesce(new.admin_note, new.failed_reason),
      auth.uid()
    );
  end if;
  return new;
end;
$$;

drop trigger if exists record_order_status_history on public.orders;
create trigger record_order_status_history
after insert or update of status on public.orders
for each row execute function public.record_order_status_history();

create or replace function public.set_initial_order_count(
  p_order_id uuid,
  p_starting_count bigint,
  p_status text,
  p_source text,
  p_message text,
  p_customer_note text default null
)
returns void
language plpgsql
security definer set search_path = public
as $$
begin
  update public.orders
  set
    starting_count = case when p_starting_count is null then null else greatest(p_starting_count, 0) end,
    current_count = case when p_starting_count is null then null else greatest(p_starting_count, 0) end,
    count_detection_status = p_status,
    count_detection_source = p_source,
    count_detection_message = p_message,
    customer_note = nullif(trim(p_customer_note), ''),
    last_count_checked_at = now()
  where id = p_order_id and user_id = auth.uid();
  if not found then raise exception 'Order not found'; end if;
end;
$$;

revoke all on function public.set_initial_order_count(uuid,bigint,text,text,text,text) from public;
grant execute on function public.set_initial_order_count(uuid,bigint,text,text,text,text) to authenticated;

