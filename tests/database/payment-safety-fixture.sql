-- In-memory test schema only. Never run this fixture against a connected database.
create role anon; create role authenticated; create role service_role bypassrls;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid
$$;
grant usage on schema auth to anon,authenticated,service_role;
grant execute on function auth.uid() to anon,authenticated,service_role;
create table profiles(id uuid primary key,email text,role text not null default 'user',balance numeric(14,2) not null default 0 check(balance>=0),updated_at timestamptz default now());
create function public.is_admin() returns boolean language sql stable security definer set search_path=public,pg_temp as $$
 select exists(select 1 from profiles where id=auth.uid() and role='admin')
$$;
grant execute on function public.is_admin() to authenticated;
create table services(id bigint generated by default as identity primary key,code text,name text,platform text,rate numeric(14,4),min integer,max integer,
 status text default 'active',is_active boolean default true,accepts_new_orders boolean default true,health_status text default 'stable');
create table customer_clients(id uuid primary key,user_id uuid,archived_at timestamptz);
create table campaigns(id uuid primary key,user_id uuid,client_id uuid);
create table orders(id uuid primary key default gen_random_uuid(),user_id uuid not null references profiles(id),service_id bigint references services(id),
 service_name text,platform text,link text,quantity integer check(quantity>0),unit_price numeric(14,4),charge numeric(14,2) not null check(charge>=0),
 status text default 'pending',payment_status text default 'paid',package_name text,client_request_id uuid,notes text,customer_note text,
 admin_note text,admin_notes text,provider_order_id text,starting_count bigint,start_count bigint,current_count bigint,
 partial_quantity_delivered bigint,remaining_count bigint,remains bigint,count_detection_status text,count_detection_source text,count_detection_message text,
 last_count_checked_at timestamptz,failed_reason text,refund_credit_note text,refill_eligible boolean default false,
 completed_at timestamptz,client_id uuid,campaign_id uuid,created_at timestamptz default now(),unique(user_id,client_request_id));
create table transactions(id uuid primary key default gen_random_uuid(),user_id uuid references profiles(id),amount numeric(14,2) not null check(amount>0),
 type text not null check(type in ('credit','debit','refund')),status text default 'pending',payment_method text,provider_order_id text unique,
 provider_payment_id text unique,provider_refund_id text,description text,metadata jsonb default '{}',created_at timestamptz default now());
-- These are the existing production policy expressions, tested without service-role bypass.
alter table profiles enable row level security;
alter table orders enable row level security;
alter table transactions enable row level security;
create policy profiles_select_own_or_admin on profiles for select to authenticated using(id=auth.uid() or public.is_admin());
create policy profiles_update_admin on profiles for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy orders_select_own_or_admin on orders for select to authenticated using(user_id=auth.uid() or public.is_admin());
create policy orders_admin_update on orders for update to authenticated using(public.is_admin()) with check(public.is_admin());
create policy transactions_select_own_or_admin on transactions for select to authenticated using(user_id=auth.uid() or public.is_admin());
grant select,update on profiles,orders,transactions to authenticated;
grant select on services,customer_clients,campaigns to authenticated;
